def make_pizza(size, *toppings):
    """Кратко описывает пиццу, которую мы собираемся приготовить."""
    print(f"\nГотовим пиццу {size} см со следующими начинками:")
    for topping in toppings:
        print(f"  - {topping}")


# Позиционные аргументы
make_pizza(30, "сыр")

# Тоже позиционные, но несколько (с распаковой через звёздочку
make_pizza(25, *("грибы", "колбаса"))

# Или просто
make_pizza(25, "Помидоры черри", "сервилад")
