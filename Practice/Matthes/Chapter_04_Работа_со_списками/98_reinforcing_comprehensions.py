# возьми следующие генераторы и запиши их словами в комментарии:

prices = [100, 250, 500, 750, 1000]

# a) Создаём новый список, для каждого p из prices умножаем на 2
result_a = [p * 2 for p in prices]

# b) Взять каждый p из prices только если p больше или равно 500
result_b = [p for p in prices if p >= 500]

# c) Для каждого p из prices "дорого" если p больше 500, иначе "дёшево"
result_c = ["дорого" if p > 500 else "дёшево" for p in prices]

# d) Взять каждое p из prices и умножить на 0.9 только если p больше 200
result_d = [p * 0.9 for p in prices if p > 200]

# e) Возьми каждую p из prices, раздели на 3, округли до 2 знаков, собери в новый список
result_e = [round(p / 3, 2) for p in prices]

# Выводим результаты:
print(f"Первоначальный список: {prices}")
print(f"Создаём новый список, для каждого p из prices умножаем на 2: {result_a}")
print(f"Берём каждый p из prices только если p больше или равно 500: {result_b}")
print(f"Для каждого p из prices 'дорого' если p больше 500, иначе 'дёшево': {result_c}")
print(f"Взять каждое p из prices и умножить на 0.9 только если p больше 200: {result_d}")
print(f"Возьми каждую p из prices, раздели на 3, округли до 2 знаков, собери в новый список: {result_e}")


