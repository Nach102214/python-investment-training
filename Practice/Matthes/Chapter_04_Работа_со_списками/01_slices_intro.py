# Срез (slice) — это часть списка. Ты как будто берёшь ножницы и отрезаешь кусок.
# Синтаксис:
# список[начало:конец]
# Важно: начало включается, а конец — НЕ включается. Это то же самое, что в range().
# Пример:
prices = [250.50, 180.20, 4500.00, 12000.00, 550.75]
#           [0]     [1]     [2]     [3]       [4]

prices[1:3]  # берём с индекса 1 по индекс 3 (не включая 3)
# → [180.20, 4500.00]
# Почему так? Потому что длина среза = конец - начало. Для [1:3] это 3 - 1 = 2 элемента. Удобно для математики.

# Список цен на акции
prices = [250.50, 180.20, 4500.00, 12000.00, 550.75]

# Список тикеров (для наглядности)
tickers = ["SBER", "GAZP", "LKOH", "GMKN", "ROSN"]

# 1. Первые три элемента
first_three_prices = prices[:3]   # с начала до индекса 3 (не включая)
first_three_tickers = tickers[:3]
print("Первые три цены:", first_three_prices)
print("Первые три тикера:", first_three_tickers)

# 2. Последние два элемента
last_two_prices = prices[-2:]     # с индекса -2 до конца
last_two_tickers = tickers[-2:]
print("\nПоследние две цены:", last_two_prices)
print("Последние два тикера:", last_two_tickers)

# 3. Средние элементы (со 2-го по 4-й, не включая 4-й)
middle_prices = prices[1:3]       # индексы 1 и 2
print("\nСредние цены (индексы 1, 2):", middle_prices)

# 4. Все элементы, начиная с индекса 2
from_third = prices[2:]           # с индекса 2 до конца
print("\nЦены с индекса 2:", from_third)

# 5. Все элементы до индекса 3
to_third = prices[:3]             # с начала до индекса 3
print("\nЦены до индекса 3:", to_third)

# 6. Полная копия списка
copy_prices = prices[:]           # ВАЖНО: это копия, а не ссылка!
print("\nКопия цен:", copy_prices)

# 7. Проверим, что копия независима от оригинала
copy_prices.append(999.99)
print("\nОригинал после изменения копии:", prices)         # 999.99 не появится
print("Копия после изменения:", copy_prices)             # 999.99 появится

prices = [250.50, 180.20, 4500.00, 12000.00, 550.75]

# Каждый второй элемент (индексы 0, 2, 4)
every_second = prices[::2]
print("Каждый второй:", every_second)  # [250.5, 4500.0, 550.75]

# Каждый третий элемент (индексы 0, 3)
every_third = prices[::3]
print("Каждый третий:", every_third)   # [250.5, 12000.0]

# Элементы в обратном порядке
reversed_prices = prices[::-1]
print("Обратный порядок:", reversed_prices)  # [550.75, 12000.0, 4500.0, 180.2, 250.5]

# Применение срезов к портфелю
# Теперь практический пример. Давай возьмём портфель из 5 акций и сделаем топ-3 по цене.
tickers = ["SBER", "GAZP", "LKOH", "GMKN", "ROSN"]
prices = [250.50, 180.20, 4500.00, 12000.00, 550.75]

# Шаг 1: сортируем тикеры по цене (сортируем пары через zip)
pairs = list(zip(prices, tickers))  # [(250.5, 'SBER'), (180.2, 'GAZP'), ...]
pairs_sorted = sorted(pairs, reverse=True)  # от дорогих к дешёвым
print(f"\nОтсортированный список пар, сшитых с помощью zip:\n{pairs_sorted}")

# Шаг 2: берём топ-3
top_3 = pairs_sorted[:3]
print("\nТоп-3 самых дорогих акций:")
for price, ticker in top_3:
    print(f"{ticker}: {price:.2f} руб.")






























