# Задача 1: Подсчёт слов по первой букве (разминка)
# Дано:
# words = ["кот", "пёс", "кот", "кит", "пёс", "кот", "попугай", "пингвин"]
# Нужно: сгруппировать слова по первой букве. Для каждой буквы — список слов, которые с неё начинаются.
# Ожидаемый результат:
# к: ['кот', 'кот', 'кит', 'кот']
# п: ['пёс', 'пёс', 'попугай', 'пингвин']
# Подсказка: здесь значение в словаре — список, а не число. Логика та же:
#     если буквы нет → создать ключ со списком из одного слова;
#     если буква есть → добавить слово в существующий список.

words = ["кот", "пёс", "кот", "кит", "пёс", "кот", "попугай", "пингвин"]

grouped_words = {}
for word in words:  # Проходим циклом по всему списку
    first_letter = word[0]  # Переменная для первого символа каждого слова в списке
    if first_letter not in grouped_words:
        # Если буква ещё нет в словаре, то создаём новый список с текущим словом
        grouped_words[first_letter] = [word]
    # Если буква уже есть в словаре, добавляем слово в существующий список
    else:
        grouped_words[first_letter].append(word)

# Выводим результат:
for letter, word_list in grouped_words.items():
    print(f"{letter}: {word_list}")


# Задача 2: Подсчёт количества акций по секторам
# Дано: тот же портфель из главы 6
# Нужно: сгруппировать количество акций (не стоимость!) по секторам.
# Ожидаемый результат:
# Финансы: 100 шт.
# Нефть и газ: 80 шт.
# Металлургия: 5 шт.
# Подсказка: это тот же код, что и в Задаче 4 из домашней работы, но вместо cost = price * quantity используйте cost = quantity. Убедитесь, что паттерн работает без изменений.

portfolio = [
    {"ticker": "SBER", "price": 250.50, "quantity": 100, "sector": "Финансы"},
    {"ticker": "GAZP", "price": 180.20, "quantity": 50, "sector": "Нефть и газ"},
    {"ticker": "LKOH", "price": 4500.00, "quantity": 10, "sector": "Нефть и газ"},
    {"ticker": "GMKN", "price": 12000.00, "quantity": 5, "sector": "Металлургия"},
    {"ticker": "ROSN", "price": 550.75, "quantity": 20, "sector": "Нефть и газ"},
]
# Создаём пустой словарь для хранения итоговых количеств акций по секторам:
sectors = {}

for stock in portfolio:
    # Достаём из текущей акции название сектора (например, строку "Финансы")
    sector = stock["sector"]

    # Достаём количество акций этой позиции (переменную назвали qty)
    qty = stock["quantity"]

    # Проверяем: если такого сектора ещё нет в словаре sectors,
    # то создаем этот ключ и записываем туда текущее количество:
    if sector not in sectors:
        sectors[sector] = qty

    # Если сектор уже есть в словаре sectors,
    # то прибавляем новое количество к уже накопленному значению:
    else:
        sectors[sector] += qty

# Пустая строка для отделения от предыдущей задачи:
print()
# Выводим результат, поочередно перебирая пары "сектор - общее количество":
for sector, qty in sectors.items():
    print(f"В секторе {sector}: {qty} акций.")


# Задача 3: Группировка тикеров по секторам (список в значении)
# Дано: тот же портфель.
# Нужно: сгруппировать тикеры по секторам. Для каждого сектора — список тикеров.
# Ожидаемый результат:
#
# Финансы: ['SBER']
# Нефть и газ: ['GAZP', 'LKOH', 'ROSN']
# Металлургия: ['GMKN']
#
# Подсказка: это комбинация Задачи 1 и Задачи 2. Значение в словаре — список, и вы добавляете в него тикеры через .append().

portfolio = [
    {"ticker": "SBER", "price": 250.50, "quantity": 100, "sector": "Финансы"},
    {"ticker": "GAZP", "price": 180.20, "quantity": 50, "sector": "Нефть и газ"},
    {"ticker": "LKOH", "price": 4500.00, "quantity": 10, "sector": "Нефть и газ"},
    {"ticker": "GMKN", "price": 12000.00, "quantity": 5, "sector": "Металлургия"},
    {"ticker": "ROSN", "price": 550.75, "quantity": 20, "sector": "Нефть и газ"},
]
# Создаём пустой словарь для хранения итоговых списков тиккеров по секторам:
sectors = {}

for stock in portfolio:
    # Достаём из текущей акции в портфеле название сектора:
    sector = stock["sector"]

    # Достаём тиккер текущей акции в портфеле:
    ticker = stock["ticker"]

    # Проверяем, есть ли такой сектор в словаре:
    if sector in sectors:
        # Если есть, то то добавляем тиккер к списку тиккеров этого сектора:
        sectors[sector].append(ticker)
    else:
        # Если нет, то создаём этот ключ и записываем туда значение тиккера:
        sectors[sector] = [ticker]

# Выводим результат:
# Пустая строка для отделения задачи от предыдущей:
print()
for sector, ticker in sectors.items():
    print(f"{sector}: {ticker}")
