# Задача 3: Проверка нескольких запросов
#     Есть список wanted = ["SBER", "AAPL", "GAZP", "TSLA", "LKOH"].
#     Есть список allowed = ["SBER", "GAZP", "LKOH", "GMKN"].
#     Для каждой акции из wanted:
#         Если в allowed — "Покупаем X".
#         Если нет — "X недоступна".
#     В конце выведи количество купленных акций.

wanted = ["SBER", "AAPL", "GAZP", "TSLA", "LKOH"]
allowed = ["SBER", "GAZP", "LKOH", "GMKN"]
quantity_purchased = 0

print()  # Пустая строка для отделения  от предыдущей задачи
for stock in wanted:
    if stock in allowed:
        print(f"Покупаем {stock}.")
        quantity_purchased += 1
    else:
        print(f"{stock} недоступна.")
print(f"Количество купленных акций - {quantity_purchased}")

# Задача 4: Калькулятор скидки
#     Есть сумма покупки amount.
#     Правила:
#         >= 100_000 → скидка 10%.
#         >= 50_000 → скидка 7%.
#         >= 10_000 → скидка 5%.
#         < 10_000 → скидка 0%.
#     Выведи сумму с учётом скидки.
# пример вывода:
# Сумма: 75_000.00 руб.
# Скидка: 7%
# Итог: 69_750.00 руб.

amount = 100_001

if amount >= 100_000:
    discount = 0.10
elif amount >= 50_000:
    discount = 0.07
elif amount >= 10_000:
    discount = 0.05
final = amount * (1 - discount)

print(f"\nСумма: {amount:_.2f} руб.")
print(f"Скидка: {discount * 100}%")
print(f"Итог: {final:_.2f} руб.")
