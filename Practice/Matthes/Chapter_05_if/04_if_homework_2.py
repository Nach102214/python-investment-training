# Задача 1: Классификация акций по цене
#     Есть список цен prices = [150.50, 850.00, 1200.00, 15000.00, 300.00].
#     Для каждой цены определи категорию:
#         < 500 → "Дешёвая"
#         < 1000 → "Средняя"
#         < 5000 → "Дорогая"
#         >= 5000 → "Премиум"
#     Выведи каждую цену с категорией.
# Проверим так же на последнее условие, дляя чего добавим в список цену ровно 5000
prices = [150.50, 850.00, 1200.00, 15000.00, 300.00, 5000.00]
# category = ""  если есть необходимость использовать переменную вне цикла

for price in prices:
    if price < 500:
        category = "Дешёвая"
    elif price < 1000:
        category = "Средняя"
    elif price < 5000:
        category = "Дорогая"
    else:
        category = "Премиум"
    print(f"{price} - {category}")

