# Задача:
# Пауза через пустой цикл (из книги)
# В книге (стр. 13, 15) есть забавная задача — сделать паузу в программе через «пустой цикл».
#     «Пустой цикл» — цикл, тело которого ничего не делает, но счётчик крутится N раз.

import time

# Способ 1: через цикл с параметром
print("Способ 1: цикл с параметром...")
start = time.time()
for i in range(26_109_000):
    pass   # ничего не делаем
print(f"  Прошло: {time.time() - start:.3f} сек")

# Способ 2: через time.sleep — «правильный» способ
print("\nСпособ 2: time.sleep(1)...")
start = time.time()
time.sleep(1)
print(f"  Прошло: {time.time() - start:.3f} сек")
