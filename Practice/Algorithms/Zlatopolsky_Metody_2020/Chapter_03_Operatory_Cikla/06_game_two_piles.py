rules_of_the_game = '''Есть две кучки спичек. Игрок, делая ход, может взять 
только из одной из двух кучек любое количество спичек от одной до всех сразу.
Выигрывает тот игрок, после хода которого ни в одной из кучек не останется спичек
'''
# Выводим правила игры:
print(rules_of_the_game)

pile1 = int(input("Сколько спичек положим в первую кучку? Введите число: "))
pile2 = int(input("Сколько спичек положим во вторую кучку? Введите число: "))

print(f"Игра началась! В первой кучке {pile1} спичек, во второй {pile2}.")

while pile1 > 0 or pile2 > 0:
    # ===== ХОД ИГРОКА 1 =====
    print(f"\nХод Игрока 1. Кучка 1: {pile1}, кучка 2: {pile2}")
    # Вложенный цикл проверки для Игрока 1:
    while True:
        choice = int(input("Из какой кучки (1 или 2) берёте спички? "))
        amount = int(input("Сколько спичек берёте? "))

        if choice != 1 and choice != 2:
            print("Ошибка! Введите 1 или 2 для выбора кучки.")
            continue
        if amount <= 0:
            print("Ошибка! Вы должны забрать из кучки хотя бы одну спичку!")
            continue
        if choice == 1 and amount > pile1:
            print(f"Ошибка! В кучке 1 нет столько спичек. Введите число не больше {pile1}.")
            continue
        if choice == 2 and amount > pile2:
            print(f"Ошибка! В кучке 2 нет столько спичек. Введите число не больше {pile2}")
            continue
        
        # Если все проверки пройдены и данные введены корректно, выходим из цикла проверки Игрока 1:
        break
    
    # Уменьшаем количество спичек в кучке:
    if choice == 1:
        pile1 = pile1 - amount
    else:
        pile2 = pile2 - amount

    # Проверяем конец игры:
    if pile1 == 0 and pile2 == 0:
        print("\nКонец игры! Игрок 1 победил!")
        break

    # ===== ХОД ИГРОКА 2 =====
    print(f"\nХод Игрока 2. Кучка 1: {pile1}, кучка 2: {pile2}")
    # Вложенный цикл проверки для Игрока 1:
    while True:
        choice = int(input("Из какой кучки (1 или 2) берёте спички? "))
        amount = int(input("Сколько спичек берёте? "))

        if choice != 1 and choice != 2:
            print("Ошибка! Введите 1 или 2 для выбора кучки.")
            continue
        if amount <= 0:
            print("Ошибка! Вы должны забрать из кучки хотя бы одну спичку!")
            continue
        if choice == 1 and amount > pile1:
            print(f"Ошибка! В кучке 1 нет столько спичек. Введите число не больше {pile1}.")
            continue
        if choice == 2 and amount > pile2:
            print(f"Ошибка! В кучке 2 нет столько спичек. Введите число не больше {pile2}")
            continue
        
        # Если все проверки пройдены и данные введены корректно, выходим из цикла проверки Игрока 2:
        break
    
    # Уменьшаем количество спичек в кучке:
    if choice == 1:
        pile1 = pile1 - amount
    else:
        pile2 = pile2 - amount

    # Проверяем конец игры:
    if pile1 == 0 and pile2 == 0:
        print("\nКонец игры! Игрок 2 победил!")
        break

print("Игра окончена!")












