# Задача определения наибольшего
# общего делителя (НОД) двух натуральных чисел.
#
# ВЕРСИЯ 3: Оптимизированный алгоритм Евклида
#
# ИДЕЯ:
# В версии 2 мы многократно ВЫЧИТАЛИ меньшее число из большего.
# Например, для 48 и 18:  48 - 18 - 18 = 12
# Это можно заменить одной операцией — ВЗЯТИЕМ ОСТАТКА:
#                        48 % 18 = 12
#
# МАТЕМАТИЧЕСКОЕ ТОЖДЕСТВО (рекуррентное соотношение):
#     НОД(a, b) = НОД(b, a mod b)
# Работает до тех пор, пока b не станет равным нулю.
# Когда b == 0, ответ находится в переменной a.
#
# ЗАЩИТА ОТ ОТРИЦАТЕЛЬНЫХ ЧИСЕЛ:
# берём модуль при вводе (см. версию 2).

a = abs(int(input("Задайте первое число 'a': ")))
b = abs(int(input("Задайте первое число 'b': ")))

while b != 0:
    # ОДНА СТРОКА, КОТОРАЯ ЗАМЕНЯЕТ ЦЕЛЫЙ БЛОК ВЫЧИТАНИЙ:
    #
    # 1. Сначала вычисляется ВСЯ правая часть как кортеж:
    #        (b, a % b)     — использует СТАРЫЕ a и b
    #
    # 2. Потом кортеж распаковывается в новые значения:
    #        a = старое b
    #        b = a % b
    #
    # Пример для a=48, b=18:
    #   До:    a=48, b=18
    #   Прав.: (18, 48 % 18) = (18, 12)
    #   После: a=18, b=12
    a, b = b, a % b

# Когда b стало равно 0, в переменной a — искомый НОД.
print(f"НОД = {a}")
