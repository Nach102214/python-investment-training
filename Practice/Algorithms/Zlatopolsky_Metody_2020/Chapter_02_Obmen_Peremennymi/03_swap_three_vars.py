# Задача:
#     Даны значения трёх переменных a, b и c. Требуется составить программу, после выполнения которой переменная b будет иметь значение переменной a, переменная c — значение переменной b, а переменная a — значение переменной c.

# Проще говоря — циклический сдвиг:
#
# Было:   a=1, b=2, c=3
# Стало:  a=3, b=1, c=2

# При циклическом сдвиге вправо (a=3, b=1, c=2) логика должна быть следующей:
# • Переменная c должна уйти в a
# • Переменная a должна уйти в b
# • Переменная b должна уйти в c
# Поскольку мы сдвигаем всё по цепочке, нам достаточно сохранить всего одно значение, которое затрётся первым. Давайте сохраним c.

a, b, c = 1, 2, 3

print("Способ. Через временную переменную: ")

print(f"До обмена:    a = {a}, b = {b}, c = {c}")

temp = c  # Шаг 1: Спасаем значение 'c' (temp = 3)
c = b     # Шаг 2: В 'c' записываем 'b' (теперь c = 2)
b = a     # Шаг 3: В 'b' записываем 'a' (теперь b = 1)
a = temp  # Шаг 4: В 'a' возвращаем спасенное значение из temp (теперь a = 3)

print(f"После обмена: a = {a}, b = {b}, c = {c}")

print("\nСпособ. Через распаковку кортежа: ")

print(f"До обмена:    a = {a}, b = {b}, c = {c}")

a, b, c = c, a, b  
# Значения сдвигаются:   c → a,   a → b,   b → c
# В правой части перечисляем их в порядке получения:
#   a получает c,  b получает a,  c получает b

print(f"После обмена: a = {a}, b = {b}, c = {c}")










