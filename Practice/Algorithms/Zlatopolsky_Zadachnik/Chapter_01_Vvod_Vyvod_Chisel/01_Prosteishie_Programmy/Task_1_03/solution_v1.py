# Задача 1.3.  Составить программу вывода на экран числа, вводимого с клавиатуры.

# Условие
# Выводимому числу должно предшествовать сообщение "Вы ввели число".

while True:
    text = input("Введите число: ")

    if not text.isdigit():
        print("Неверный ввод!")
        continue
    else:
        num = int(text)
        print(f"Вы ввели число {num}")
        break
