# Задача 1.1 
#    Вывести на экран число π с точностью до сотых
# V1 Округляем с помощью format(), устаревший способ, но часто встречается 
# в старых проектах:

import math                     # Импорт модуля

# Выводим на экран с помощью форматированного вывода:
print("Значение Пи с двумя знаками после запятой: {:.2f}".format(math.pi))
