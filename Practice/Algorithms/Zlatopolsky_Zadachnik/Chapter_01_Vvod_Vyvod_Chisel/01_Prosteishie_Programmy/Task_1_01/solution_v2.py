# Задача 1.1 
#    Вывести на экран число π с точностью до сотых
# V1 Округляем с помощью функции round():

import math                     # Импорт модуля

pi = round(math.pi, 2)          # Присваиваем значение

# Вывод на печать уже с округлением:
print("Значение числа Пи с округлением до двух знаков после запятой:", pi)
