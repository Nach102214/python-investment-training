# Задача 1.1 
#    Вывести на экран число π с точностью до сотых
# V1 Округляем с помощью f-строки (современный метод):

import math                     # Импорт модуля

pi = math.pi                    # Присваиваем значение

# Вывод на печать с округлением через f-строку:
print(f"Значение числа Пи с округлением до двух знаков после запятой: {pi:.2f}")
