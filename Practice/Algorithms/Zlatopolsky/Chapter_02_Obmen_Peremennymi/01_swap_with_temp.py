# Задача: Даны значения двух переменных a и b.
# Требуется произвести взаимный обмен их значений.

# Надо действовать так, как производят обмен содержи-
# мого двух чашек, в одной из которых находится молоко, а в другой —
# чай. Нужна третья чашка!


a = 5
b = 10

print(f"До обмена:    a = {a}, b = {b}")

# Обмен через временную переменную
temp = a
a = b
b = temp

print(f"После обмена: a = {a}, b = {b}")
