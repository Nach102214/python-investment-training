# Задача: Даны значения двух переменных a и b.
# Требуется произвести взаимный обмен их значений.

a = -5
b = 10

print(f"До обмена:    a = {a}, b = {b}")

# Через сложение и вычитание
# Самый классический способ, который проходят в университетах.

a = a + b    # теперь a = сумма
b = a - b    # b = (a+b) - b = старое a
a = a - b    # a = (a+b) - старое a = старое b

# ⚠️ ПОДВОХ арифметического способа:
# 1. НЕ работает для строк:
#       a = "hello"; b = "world"
#       a = a + b   # "helloworld"
#       b = a - b   # ОШИБКА! Строки нельзя вычитать
# 2. В языках с фиксированным размером int (C, Java) может
#    произойти переполнение, если a + b превысит максимум.
# 3. Для float возможна потеря точности на больших числах.
# Распаковка кортежа a, b = b, a работает ВСЕГДА и для любого типа.

print(f"После обмена: a = {a}, b = {b}")


# Ещё способ - через распаковку кортежа (Python-стиль):
# Что здесь происходит:
#
#     Правая часть b, a вычисляется как кортеж: (10, 5).
#
#     Кортеж распаковывается в переменные: a = 10, b = 5.

print(f"\nДо обмена:    a = {a}, b = {b}")

a, b = b, a

print(f"После обмена: a = {a}, b = {b}")






