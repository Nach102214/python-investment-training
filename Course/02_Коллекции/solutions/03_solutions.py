# **B5.** 💡 Пользователь вводит путь к файлу, например `"/home/nach101/report.csv"`. Выведи:
# - имя файла (`"report.csv"`)
# - расширение (`"csv"`)
# - имя без расширения (`"report"`)
# - каталог (`"/home/nach101"`)
#
# **Подсказка:** `.split("/")`, `.rsplit(".", 1)`, `"/".join(...)`.
# **Нарисуй схему в `Mermaid/B05.md`.**

user_input = "/home/nach101/report.csv"

# Разбиваем путь по "/"
parts = user_input.split("/")

# Имя файла — это последний элемент списка
file_name = parts[-1]

# Делим имя файла по последней точке
# rsplit(sep, 1) делает ровно одно разделение справа
name_without_extension, extension = file_name.rsplit(".", 1)

# Каталог — это все части, кроме последней, соединяем их через "/"
catalog = "/".join(parts[:-1])

print(f"\nИмя файла: {file_name}")
print(f"Расширение: {extension}")
print(f"Имя без расширения: {name_without_extension}")
print(f"Каталог: {catalog}")


