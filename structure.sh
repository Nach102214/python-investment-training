# 01. Переменные и типы данных

## Что такое переменная?
Переменная — это **имя**, за которым стоит **значение**. В Python не нужно
объявлять тип — он определяется автоматически.

```python
x = 42          # int
price = 99.90   # float
name = "AAPL"   # str
active = True   # bool
